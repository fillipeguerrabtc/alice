/**
 * Registro central de ações agentic (Trading e operações correlatas)
 *
 * Fonte única de governança para:
 * - endpoint/verbos
 * - nível de risco
 * - necessidade de aprovação
 * - permissões RBAC
 *
 * Documentação em PT-BR (Regra 10 CLAUDE.md).
 */

export type AgenticService =
  | 'trading'
  | 'payments'
  | 'grafana'
  | 'stack_ops'
  | 'agentic_task';

export type AgenticRiskLevel = 'low' | 'medium' | 'high' | 'critical';

export type AgenticApprovalRequirement = 'never' | 'always' | 'risk_based';

export type AgenticActionDefinition = {
  id: string;
  service: AgenticService;
  method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
  path: string;
  riskLevel: AgenticRiskLevel;
  approval: AgenticApprovalRequirement;
  permissions: string[];
  requiredFields?: string[];
  uiCardType: 'read' | 'write' | 'approval' | 'task';
};

