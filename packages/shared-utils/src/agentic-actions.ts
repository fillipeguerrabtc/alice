export const AGENTIC_ACTION_REGISTRY: AgenticActionDefinition[] = [
  ...TRADING_READ,
  ...TRADING_WRITE,
];

export function getAgenticActionById(actionId: string): AgenticActionDefinition | undefined {
  return AGENTIC_ACTION_REGISTRY.find((item) => item.id === actionId);
}

export function listAgenticActionsByService(service: AgenticService): AgenticActionDefinition[] {
  return AGENTIC_ACTION_REGISTRY.filter((item) => item.service === service);
}
